import { evaluate, sensitive, selectCandidates, validTargets } from './core.mjs';
import { credential, requestDecision, providerConfig } from './client.mjs';

// Caller binds the actual app/tab via documented CUA first. No app discovery,
// launching, arbitrary JS execution, coordinates, shell broker, or extra TCC.
export const createCuaDriver = target => ({
  observe: () => target.getAXState({ emit: false, disableDiffing: true }),
  click: index => target.click(index),
  setValue: (index, value) => target.setValue(index, value),
});
const safe = promise => Promise.resolve(promise).then(value => ({ ok: true, value })).catch(() => ({ ok: false }));
const verifyState = (verify, ax) => safe(Promise.resolve().then(() => verify(ax))).then(r => r.ok ? { ok: true, verified: r.value === true } : { ok: false });

/** One authorized phase. Exact observed labels bound what the selector can do.
 * verify must check the intended result, not the existence of its control.
 * egressApproved applies ONLY to goal + the allowlisted labels sent to the explicitly selected provider.
 * text is supplied by the planner, kept local, and never generated by Jev.
 */
export const runPhase = async ({ driver, goal, targets, verify, action = 'click', text,
  execute = false, authorized = false, egressApproved = false, keyFile, provider = 'typesafe',
  maxSteps = 3, maxMs = 15000, threshold = 0.8, onEvent = () => {},
  decide, // Test adapter only; production leaves this undefined.
}) => {
  const started = performance.now();
  const finish = (status, reason, steps, verified = false) => ({ status, reason, steps, verified, elapsedMs: Math.round(performance.now() - started) });
  const invalid = !providerConfig(provider) || typeof goal !== 'string' || goal.length < 1 || goal.length > 500 || !validTargets(targets) || typeof verify !== 'function'
    || !['click', 'setValue'].includes(action) || (action === 'setValue' && (typeof text !== 'string' || text.length > 10000))
    || !Number.isInteger(maxSteps) || maxSteps < 1 || maxSteps > 10 || !Number.isFinite(maxMs) || maxMs < 1000 || maxMs > 30000
    || !Number.isFinite(threshold) || threshold < 0.8 || threshold > 1;
  if (invalid) return finish('blocked', 'invalid_phase', 0);
  if (action === 'setValue' && targets.some(t => !['text field', 'search field', 'combo box'].includes(t.role))) return finish('blocked', 'invalid_input_target', 0);
  if (execute && !authorized) return finish('blocked', 'action_not_authorized', 0);
  if (targets.some(t => sensitive(t.label))) return finish('blocked', 'consequential_action', 0);
  const initial = await safe(Promise.resolve().then(() => driver.observe()));
  if (!initial.ok) return finish('error', 'observation_failed', 0);
  const firstCheck = await verifyState(verify, initial.value);
  if (!firstCheck.ok) return finish('error', 'verification_failed', 0);
  if (firstCheck.verified) return finish('done', 'readback', 0, true);
  if (!egressApproved) return finish('blocked', 'egress_not_authorized', 0);
  const auth = decide ? { ok: true } : await credential({ keyFile, provider });
  if (!auth.ok) return finish('blocked', auth.reason, 0);
  const choose = decide ?? (input => requestDecision({ ...input, key: auth.key, provider }));
  const step = async (ax, count) => {
    if (count >= maxSteps) return finish('escalate', 'step_budget', count);
    if (performance.now() - started >= maxMs) return finish('escalate', 'time_budget', count);
    const candidates = selectCandidates(ax, targets);
    if (!candidates.length) return finish('escalate', 'no_candidates', count);
    if (new Set(candidates.map(c => c.role + '\0' + c.label)).size !== candidates.length) return finish('escalate', 'ambiguous_targets', count);
    const request = await safe(Promise.resolve().then(() => choose({ goal, candidates, timeoutMs: Math.max(1, Math.min(4000, maxMs - (performance.now() - started))) })));
    if (!request.ok || !request.value.ok) return finish('error', request.value?.reason ?? 'decision_failed', count);
    if (performance.now() - started >= maxMs) return finish('escalate', 'time_budget', count);
    const gate = evaluate({ answer: request.value.answer, candidates, threshold });
    if (gate.status !== 'selected') return finish(gate.status, gate.reason, count);
    await onEvent({ stage: 'selection', step: count + 1, action, index: gate.target.index, model: request.value.model, latencyMs: request.value.latencyMs });
    // Re-observe after network latency and any event callback. A changed tree invalidates all indices;
    // return to the planner rather than clicking an old handle.
    const fresh = await safe(Promise.resolve().then(() => driver.observe()));
    if (!fresh.ok) return finish('error', 'observation_failed', count);
    if (fresh.value !== ax) return finish('escalate', 'state_changed', count);
    if (performance.now() - started >= maxMs) return finish('escalate', 'time_budget', count);
    if (!execute) return { ...finish('preview', 'no_mutation', count), selection: gate.target, action };
    const acted = await safe(Promise.resolve().then(() => action === 'click' ? driver.click(gate.target.index) : driver.setValue(gate.target.index, text)));
    // Even an action error may have changed the target. Always attempt readback.
    const after = await safe(Promise.resolve().then(() => driver.observe()));
    if (!after.ok) return finish('unverified', 'readback_failed_do_not_retry', count + 1);
    const checked = await verifyState(verify, after.value);
    if (!checked.ok) return finish('unverified', 'verification_failed', count + 1);
    if (checked.verified) return finish('done', 'readback', count + 1, true);
    if (!acted.ok) return finish('unverified', 'action_failed_do_not_retry', count + 1);
    if (after.value === ax) return finish('escalate', 'no_change', count + 1);
    return step(after.value, count + 1);
  };
  return step(initial.value, 0);
};
